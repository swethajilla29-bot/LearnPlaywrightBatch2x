let score = 100;

if (score >= 90) {
    console.log("A grade");
} else if (score >= 80 && score <= 89) {
    console.log("B grade");
} else if (score >= 70 && score <= 79) {
    console.log("C grade");
} else if (score >= 60 && score <= 69) {
    console.log("D grade");
} else {
    console.log("Failed");
}

