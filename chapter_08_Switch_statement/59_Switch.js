let day = 2;
//if 1- mon, 2- tues

switch (day) {
    case 1:
        console.log("Mon day");
        break;
    case 2:
        console.log("Tues day");
        break;
    case 3:
        console.log("Wednes day");
        break;
    case 4:
        console.log("Thurs day");
        break;
    case 5:
        console.log("Fri day");
        break;
    case 6:
        console.log("Sat day");
        break;
    case 7:
        console.log("Sun day");
        break;
    default:
        console.log("No idea which day it is");
}